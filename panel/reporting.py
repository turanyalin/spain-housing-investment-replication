"""Create panel tables, numerical text macros, and publication figures."""

from pathlib import Path
import json
import numpy as np
import pandas as pd
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

SENSITIVITIES = [
    ("S_equipment", "Equipment investment"),
    ("S_ipp", "Intellectual property"),
    ("S_no_spain", "Exclude Spain"),
    ("S_pre2008", "1996--2007"),
    ("S_post2008", "2008--2024"),
    ("S_exclude_covid", "Exclude 2020 and 2021"),
    ("S_to2023", "End in 2023"),
    ("S_balanced", "Balanced 2010--2024"),
    ("S_country_cluster", "Country clustering only"),
]


def row(label, cells):
    return " & ".join([label, *cells]) + r"\\" + "\n"


def number(value, digits=3):
    return f"${value:.{digits}f}$"


def table(path, columns, headings, rows):
    text = "% Generated by python -m panel.run\n"
    text += r"\begin{tabularx}{\linewidth}{" + columns + "}\n\\toprule\n"
    text += (
        " & ".join(r"\textbf{" + title + "}" for title in headings)
        + r"\\"
        + "\n\\midrule\n"
    )
    text += "".join(rows) + "\\bottomrule\n\\end{tabularx}\n"
    path.write_text(text)


def write_outputs(data, coverage, results, output_dir: Path):
    output_dir.mkdir(parents=True, exist_ok=True)
    data.to_csv(output_dir / "panel_data.csv", index=False, float_format="%.12g")
    coverage.to_csv(output_dir / "country_coverage.csv", index=False)
    (output_dir / "panel_results.json").write_text(json.dumps(results, indent=2) + "\n")
    flat = []
    for model, result in results["models"].items():
        for term, values in result["coefficients"].items():
            flat.append(
                dict(
                    model=model,
                    term=term,
                    n=result["n"],
                    countries=result["country_clusters"],
                    years=result["year_clusters"],
                    inference_df=result["inference_df"],
                    clustering=result["clustering"],
                    **values,
                )
            )
    pd.DataFrame(flat).to_csv(output_dir / "panel_regressions.csv", index=False)
    models = results["models"]
    main_names = ["P1_house", "P2_gdp", "P3_lag"]
    rows = []
    for label, term in [
        ("House price growth", "g_house"),
        ("GDP growth", "g_gdp"),
        ("Lagged house price growth", "lag_house"),
    ]:
        cells = []
        for name in main_names:
            coefficient = models[name]["coefficients"].get(term)
            cells.append(
                r"\textemdash"
                if coefficient is None
                else r"\shortstack{"
                + number(coefficient["beta"])
                + r"\\"
                + f"$({coefficient['se']:.3f})$"
                + "}"
            )
        rows.append(row(label, cells))
    for label, key in [
        ("Observations", "n"),
        ("Country clusters", "country_clusters"),
        ("Year clusters", "year_clusters"),
    ]:
        rows.append(row(label, [str(models[name][key]) for name in main_names]))
    rows += [
        row("Country and year effects", ["Yes"] * 3),
        row(
            r"Within $R^2$", [number(models[name]["r2_within"]) for name in main_names]
        ),
        row(
            "House coefficient p-value",
            [
                number(models[name]["coefficients"]["g_house"]["p"])
                for name in main_names
            ],
        ),
    ]
    table(
        output_dir / "main_table.tex",
        "@{}Y r r r@{}",
        ["Regressor or statistic", "1", "2", "3"],
        rows,
    )
    rows = []
    for name, label in SENSITIVITIES:
        result = models[name]
        coefficient = result["coefficients"]["g_house"]
        rows.append(
            row(
                label,
                [
                    str(result["n"]),
                    str(result["country_clusters"]),
                    number(coefficient["beta"]),
                    f"$[{coefficient['lo']:.3f}, {coefficient['hi']:.3f}]$",
                    number(coefficient["p"]),
                ],
            )
        )
    table(
        output_dir / "sensitivity_table.tex",
        "@{}Y r r r r r@{}",
        ["Specification", "N", "Countries", "Estimate", "95 percent CI", "p-value"],
        rows,
    )
    rows = []
    for variable, label in [
        ("g_manufacturing", "Manufacturing investment"),
        ("g_house", "Real house prices"),
        ("g_gdp", "Real GDP"),
    ]:
        values = results["summary"][variable]
        rows.append(
            row(
                label,
                [
                    str(values["n"]),
                    *[
                        number(values[key], 2)
                        for key in ("mean", "sd", "minimum", "maximum")
                    ],
                ],
            )
        )
    table(
        output_dir / "summary_table.tex",
        "@{}Y r r r r r@{}",
        ["Growth series", "N", "Mean", "SD", "Min", "Max"],
        rows,
    )
    rows = [
        row(
            record.country_name + " (" + record.country + ")",
            [
                str(int(record.first_growth_year)),
                str(int(record.last_growth_year)),
                str(record.baseline_observations),
            ],
        )
        for record in coverage.sort_values("country_name").itertuples()
    ]
    table(
        output_dir / "coverage_table.tex",
        "@{}Y r r r@{}",
        ["Country", "First year", "Last year", "N"],
        rows,
    )
    baseline = models["P2_gdp"]
    coefficient = baseline["coefficients"]["g_house"]
    macros = {
        "PanelN": str(baseline["n"]),
        "PanelFullCountries": str(int(coverage.baseline_observations.eq(29).sum())),
        "PanelCountries": str(baseline["country_clusters"]),
        "PanelYears": str(baseline["year_clusters"]),
        "PanelMultiple": f"{baseline['n']/29:.1f}",
        "PanelBeta": f"{coefficient['beta']:.3f}",
        "PanelSE": f"{coefficient['se']:.3f}",
        "PanelLower": f"{coefficient['lo']:.3f}",
        "PanelUpper": f"{coefficient['hi']:.3f}",
        "PanelP": f"{coefficient['p']:.3f}",
        "PanelWithin": f"{baseline['r2_within']:.3f}",
        "PanelDof": str(baseline["inference_df"]),
        "PanelLooMin": f"{min(results['leave_one_country_out'].values()):.3f}",
        "PanelLooMax": f"{max(results['leave_one_country_out'].values()):.3f}",
    }
    (output_dir / "estimates.tex").write_text(
        "% Generated numerical text values\n"
        + "".join(
            "\\newcommand{\\" + name + "}{" + value + "}\n"
            for name, value in macros.items()
        )
    )


def make_figures(data, coverage, results, output_dir: Path):
    plt.rcParams.update(
        {
            "font.family": "DejaVu Serif",
            "font.size": 9,
            "pdf.fonttype": 42,
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )
    countries = coverage.sort_values("country_name").country.tolist()
    matrix = data.pivot(
        index="country", columns="year", values="baseline_sample"
    ).reindex(countries)
    matrix = matrix.loc[:, 1996:2024].to_numpy(dtype=int)
    fig, ax = plt.subplots(figsize=(7.1, 6.1))
    from matplotlib.colors import ListedColormap

    ax.imshow(
        matrix,
        aspect="auto",
        interpolation="nearest",
        cmap=ListedColormap(["#f0f0f0", "#334f68"]),
        vmin=0,
        vmax=1,
    )
    ax.set_yticks(
        range(len(countries)),
        [
            coverage.set_index("country").loc[country, "country_name"]
            for country in countries
        ],
    )
    ticks = [1996, 2000, 2005, 2010, 2015, 2020, 2024]
    ax.set_xticks([year - 1996 for year in ticks], ticks)
    ax.set_xlabel("Regression year; dark cells have complete growth observations")
    ax.tick_params(axis="both", length=0)
    fig.tight_layout()
    fig.savefig(output_dir / "coverage.pdf", bbox_inches="tight")
    plt.close(fig)
    items = [("P2_gdp", "Baseline panel"), *SENSITIVITIES]
    fig, ax = plt.subplots(figsize=(7.1, 4.6))
    for i, (name, label) in enumerate(items):
        c = results["models"][name]["coefficients"]["g_house"]
        ax.errorbar(
            c["beta"],
            i,
            xerr=[[c["beta"] - c["lo"]], [c["hi"] - c["beta"]]],
            fmt="o",
            color="#24485f" if i == 0 else "#777777",
            capsize=2,
            markersize=4,
        )
    ax.set_yticks(range(len(items)), [label.replace("--", "–") for _, label in items])
    ax.invert_yaxis()
    ax.axvline(0, color="#999999", lw=0.8)
    ax.grid(axis="x", alpha=0.18)
    ax.set_xlabel("House-price growth coefficient and 95% confidence interval")
    fig.tight_layout()
    fig.savefig(output_dir / "coefficients.pdf", bbox_inches="tight")
    plt.close(fig)
